#!/usr/bin/env python3
"""Print (or write) the numbers used in the README, seminar deck and docs.

Usage:
    python tools/project_stats.py
    python tools/project_stats.py --write docs/STATS.md
"""
import argparse
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECT = os.path.join(ROOT, "nakshatra")
CONTENT = os.path.join(PROJECT, "data", "content.json")
SKY = os.path.join(PROJECT, "data", "sky")


def count_lines(paths, suffix):
    files = []
    total = 0
    for base in paths:
        for dirpath, _, names in os.walk(base):
            if ".godot" in dirpath or "build" in dirpath:
                continue
            for name in names:
                if name.endswith(suffix):
                    p = os.path.join(dirpath, name)
                    files.append(p)
                    with open(p, encoding="utf-8", errors="replace") as f:
                        total += sum(1 for _ in f)
    return len(files), total


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", default="")
    args = ap.parse_args()

    data = json.load(open(CONTENT, encoding="utf-8"))
    stars = json.load(open(os.path.join(SKY, "stars.json"), encoding="utf-8"))
    cons = json.load(open(os.path.join(SKY, "constellations.json"), encoding="utf-8"))
    naks = json.load(open(os.path.join(SKY, "nakshatras.json"), encoding="utf-8"))

    gd_files, gd_lines = count_lines([os.path.join(PROJECT, "scripts"), os.path.join(PROJECT, "tests")], ".gd")
    sh_files, sh_lines = count_lines([os.path.join(PROJECT, "shaders")], ".gdshader")
    scene_files, _ = count_lines([os.path.join(PROJECT, "scenes")], ".tscn")
    art_files = len([f for f in os.listdir(os.path.join(PROJECT, "assets", "art")) if f.endswith((".webp", ".png"))])
    seminar_files = len([f for f in os.listdir(os.path.join(PROJECT, "assets", "seminar")) if f.endswith(".webp")]) if os.path.isdir(os.path.join(PROJECT, "assets", "seminar")) else 0

    web = os.path.join(PROJECT, "build", "web")
    web_sizes = {}
    for name in ["index.wasm", "index.pck", "index.js", "index.html"]:
        p = os.path.join(web, name)
        if os.path.exists(p):
            web_sizes[name] = os.path.getsize(p)
    zip_path = os.path.join(ROOT, "itch", "nakshatra-web.zip")
    zip_size = os.path.getsize(zip_path) if os.path.exists(zip_path) else 0

    words = 0
    def walk(v):
        nonlocal words
        if isinstance(v, str):
            words += len(v.split())
        elif isinstance(v, list):
            for x in v:
                walk(x)
        elif isinstance(v, dict):
            for x in v.values():
                walk(x)
    walk(data)

    def mb(n):
        return f"{n / (1024 * 1024):.1f} MB"

    rows = [
        ("Naked-eye stars in the catalogue", f"{len(stars['hips']):,}"),
        ("IAU constellations with line figures", f"{len(cons)}"),
        ("Nakshatras with line figures", f"{len(naks)}"),
        ("Learning modules", f"{len(data.get('modules', {}))}"),
        ("Sky Riddles questions", f"{len(data.get('quiz', []))}"),
        ("Field Guide cards", f"{len(data.get('wonders', []))}"),
        ("Star hunts", f"{len(data.get('star_hunts', []))}"),
        ("Planet fact sheets", f"{len(data.get('planets', []))}"),
        ("Scale riddles", f"{len(data.get('scale_riddles', []))}"),
        ("Seminar slides", f"{len(data.get('seminar', {}).get('slides', []))}"),
        ("GDScript files / lines", f"{gd_files} / {gd_lines:,}"),
        ("Shader files / lines", f"{sh_files} / {sh_lines:,}"),
        ("Scene files", f"{scene_files}"),
        ("Illustration files", f"{art_files}"),
        ("Seminar image files", f"{seminar_files}"),
        ("Words in content.json", f"{words:,}"),
    ]
    if web_sizes:
        rows.append(("Web export: wasm / pck", f"{mb(web_sizes.get('index.wasm', 0))} / {mb(web_sizes.get('index.pck', 0))}"))
    if zip_size:
        rows.append(("itch.io zip", mb(zip_size)))

    out = ["# Project stats", "", "Generated by `python tools/project_stats.py`.", "", "| Measure | Value |", "|---|---:|"]
    out += [f"| {a} | {b} |" for a, b in rows]
    out.append("")
    text = "\n".join(out)
    if args.write:
        with open(os.path.join(ROOT, args.write), "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote", args.write)
    else:
        print(text)


if __name__ == "__main__":
    main()
