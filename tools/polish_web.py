#!/usr/bin/env python3
"""Add a branded offline loading screen + mobile meta to the exported web page.

Also writes a small service worker and web app manifest, so the "works offline"
line in the loader is true: after the first successful load every asset the game
needs is in Cache Storage and a reload with the network off still starts.
"""
import json
import os
import re
import sys
import hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, "nakshatra", "build", "web")
HTML = os.path.join(BUILD, "index.html")
PCK = os.path.join(BUILD, "index.pck")
SW = os.path.join(BUILD, "sw.js")
MANIFEST = os.path.join(BUILD, "manifest.webmanifest")

with open(HTML, encoding="utf-8") as f:
    html = f.read()

# Cache-bust the pack: Godot's loader will happily serve a stale pck otherwise,
# and a shipped update would never reach returning players.
stamp = "dev"
if os.path.exists(PCK):
    stamp = hashlib.sha256(open(PCK, "rb").read()).hexdigest()[:10]
    if '"mainPack"' in html:
        html = re.sub(r'"mainPack":"index\.pck\?v=[0-9a-f]+"',
                      f'"mainPack":"index.pck?v={stamp}"', html)
    else:
        html = html.replace('"executable":"index"', f'"executable":"index","mainPack":"index.pck?v={stamp}"')

manifest = {
    "name": "Nakshatra — The Sky Weavers",
    "short_name": "Nakshatra",
    "description": "A free-choice 3D sky lab for Classes 6–9, with a twelve-slide seminar deck.",
    "lang": "en-IN",
    "start_url": "./index.html",
    "scope": "./",
    "display": "standalone",
    "orientation": "any",
    "background_color": "#060910",
    "theme_color": "#060910",
    "categories": ["education", "science"],
    "icons": [
        {"src": "index.icon.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "index.apple-touch-icon.png", "sizes": "180x180", "type": "image/png", "purpose": "any"},
    ],
    "shortcuts": [
        {"name": "Seminar deck", "short_name": "Deck", "url": "./index.html?scene=seminar"},
        {"name": "Sky Lab", "short_name": "Sky Lab", "url": "./index.html?scene=lab"},
    ],
}
with open(MANIFEST, "w", encoding="utf-8") as f:
    json.dump(manifest, f, ensure_ascii=False, indent=2)

sw = f"""// Nakshatra offline cache — generated by tools/polish_web.py.
// Everything the game needs is static; this worker makes the second visit work
// without a network. The cache name changes whenever the PCK changes.
const VERSION = 'nakshatra-{stamp}';
const ASSETS = [
  'index.html',
  'index.js',
  'index.wasm',
  'index.pck?v={stamp}',
  'index.audio.worklet.js',
  'index.audio.position.worklet.js',
  'index.icon.png',
  'index.apple-touch-icon.png',
  'index.png',
  'manifest.webmanifest'
];

self.addEventListener('install', (event) => {{
  event.waitUntil(
    caches.open(VERSION)
      .then((cache) => cache.addAll(ASSETS))
      .then(() => self.skipWaiting())
  );
}});

self.addEventListener('activate', (event) => {{
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys
        .filter((key) => key.startsWith('nakshatra-') && key !== VERSION)
        .map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
}});

self.addEventListener('fetch', (event) => {{
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(request, {{ ignoreSearch: true }}).then((hit) => {{
      if (hit) return hit;
      return fetch(request).then((response) => {{
        if (response && response.ok) {{
          const copy = response.clone();
          caches.open(VERSION).then((cache) => cache.put(request, copy));
        }}
        return response;
      }}).catch(() => {{
        if (request.mode === 'navigate') {{
          return caches.match('index.html');
        }}
        return new Response('', {{ status: 503, statusText: 'Offline' }});
      }});
    }})
  );
}});
"""
with open(SW, "w", encoding="utf-8") as f:
    f.write(sw)


def add_manifest_and_sw(doc: str) -> str:
    if 'id="nk-manifest"' not in doc:
        link = '\t\t<link id="nk-manifest" rel="manifest" href="manifest.webmanifest">\n'
        doc = doc.replace("\t</head>", link + "\t</head>", 1)
    if 'id="nk-sw"' not in doc:
        script = '''\t\t<script id="nk-sw">
\t\t\tif ('serviceWorker' in navigator) {
\t\t\t\twindow.addEventListener('load', function () {
\t\t\t\t\tnavigator.serviceWorker.register('sw.js').catch(function () {});
\t\t\t\t});
\t\t\t}
\t\t</script>
'''
        doc = doc.replace("\t</body>", script + "\t</body>", 1)
    return doc


if "nk-loader" in html:
    html = add_manifest_and_sw(html)
    with open(HTML, "w", encoding="utf-8") as f:
        f.write(html)
    print("already polished (pack stamp, manifest and worker refreshed)")
    sys.exit(0)

